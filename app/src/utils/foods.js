/**
 * Search the local food database.
 * Matches against the food name (case-insensitive, partial) and filters by
 * category when one is given. Returns an array of matching foods, capped at 30.
 */
export function searchLocalFoods(query = '', category = 'all') {
  const q = query.trim().toLowerCase();
  const matches = FOODS.filter(food => {
    if (category !== 'all' && food.category !== category) return false;
    if (!q) return true;
    return food.name.toLowerCase().includes(q);
  });
  return matches.slice(0, 30);
}

/** Distinct categories present in the local food database. */
export function getFoodCategories() {
  const seen = [];
  FOODS.forEach(food => {
    if (!seen.includes(food.category)) seen.push(food.category);
  });
  return seen;
}
